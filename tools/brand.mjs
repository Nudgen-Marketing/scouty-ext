// Copies the Scouty mark and outlined wordmark from the app into src/ui/brand.ts.
// Usage: npm run brand [-- path/to/scouty]   (default: ../scouty, the app checked out next to this repo)
// The three export lines are copied byte for byte from the app's src/lib/brand-mark.ts; the
// static test compares them again whenever the app is checked out next to this repository.
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const BRAND_SOURCE = "src/lib/brand-mark.ts";
export const BRAND_EXPORTS = ["BRAND_MARK_PATHS", "BRAND_WORD_PATHS", "BRAND_LOGO_WIDTH"];

/** The `export const NAME = …;` line of each brand export, in a fixed order. */
export function brandLines(source) {
  return BRAND_EXPORTS.map((name) => {
    const line = source.split("\n").find((l) => l.startsWith(`export const ${name} = `));
    if (!line) throw new Error(`${name} not found in ${BRAND_SOURCE}`);
    return line;
  });
}

export function brandTs(source, commit) {
  return `// GENERATED by tools/brand.mjs from the Scouty app, ${BRAND_SOURCE} at commit ${commit}. Do not edit:
// change the app, then run \`npm run brand\`. The Scouty mark (two open conversation shapes forming
// an S, viewBox 0 0 40 40) and the outlined "scouty" wordmark (viewBox 0 0 BRAND_LOGO_WIDTH 60,
// with the mark drawn at translate(2 7)). Owner decision 2026-11-24: the logo may be published here.
${brandLines(source).join("\n")}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const app = path.resolve(process.argv[2] ?? path.join(root, "..", "scouty"));
  const source = await readFile(path.join(app, BRAND_SOURCE), "utf8");
  const commit = execFileSync("git", ["log", "-1", "--format=%h", "--", BRAND_SOURCE], { cwd: app, encoding: "utf8" }).trim() || "unknown";
  await writeFile(path.join(root, "src/ui/brand.ts"), brandTs(source, commit));
  console.log(`wrote src/ui/brand.ts from ${BRAND_SOURCE} at ${commit}`);
}
