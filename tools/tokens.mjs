// Writes src/ui/tokens.css from src/ui/tokens.json (the token subset exported from the app).
// tokens.css is the only place in the extension that holds a colour value.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

function block(theme, pills) {
  const lines = Object.entries(theme).map(([name, value]) => `  --${name}: ${value};`);
  for (const [tone, parts] of Object.entries(pills)) for (const [part, value] of Object.entries(parts)) lines.push(`  --pill-${tone}-${part}: ${value};`);
  return lines.join("\n");
}

export function tokensCss(tokens) {
  const light = block(tokens.light, tokens.pill.light);
  const dark = block(tokens.dark, tokens.pill.dark);
  return `/*
 * GENERATED by tools/tokens.mjs from src/ui/tokens.json. Do not edit.
 * Source: the Scouty app, ${tokens.source.file} at commit ${tokens.source.commit}
 * (status-pill tones: ${tokens.source.pills}).
 * The only colour values in the extension live here. :root serves the popup, :host the in-page
 * overlay's shadow root, and [data-theme] lets the state gallery show both themes side by side.
 */
:root,
:host {
  --radius: ${tokens.radius};
${light}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]),
  :host(:not([data-theme="light"])) {
${dark.replace(/^/gm, "  ")}
  }
}

[data-theme="light"],
:host([data-theme="light"]) {
${light}
}

[data-theme="dark"],
:host([data-theme="dark"]) {
${dark}
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(await readFile(path.join(root, "src/ui/tokens.json"), "utf8"));
  await writeFile(path.join(root, "src/ui/tokens.css"), tokensCss(tokens));
  console.log("wrote src/ui/tokens.css");
}
